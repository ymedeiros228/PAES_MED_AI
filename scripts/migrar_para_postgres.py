"""Copia o banco SQLite do app para o Postgres (Supabase) da versão web.

Uso (na raiz do repositório):
    python scripts/migrar_para_postgres.py                  # data/paes_med_ai.db → esquema public
    python scripts/migrar_para_postgres.py --schema teste   # esquema descartável para rodar os testes
    python scripts/migrar_para_postgres.py --sqlite outro.db --recriar

Lê DATABASE_URL do backend/.env. O esquema sai do próprio SQLite (PRAGMA), então
colunas acrescentadas ao longo do tempo (ex.: materials.pdf_filename) vêm junto.
Todas as tabelas ficam com RLS ligado e sem política: a chave pública do Supabase
não lê nem grava nada; só o backend (usuário postgres) acessa.
"""

from __future__ import annotations

import argparse
import os
import re
import sqlite3
import sys
from pathlib import Path

RAIZ = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(RAIZ / "backend"))

import psycopg  # noqa: E402
from dotenv import load_dotenv  # noqa: E402

TIPOS = {"INTEGER": "bigint", "REAL": "double precision", "TEXT": "text", "BLOB": "bytea", "": "text"}


def tipo_pg(declarado: str) -> str:
    return TIPOS.get(declarado.upper().split("(")[0].strip(), "text")


def ler_tabelas(src: sqlite3.Connection) -> list[dict]:
    tabelas = []
    for nome, sql in src.execute(
        "SELECT name, sql FROM sqlite_master WHERE type='table' AND name NOT LIKE 'sqlite_%' ORDER BY name"
    ):
        cols = src.execute(f'PRAGMA table_info("{nome}")').fetchall()
        pk = [c[1] for c in sorted((c for c in cols if c[5]), key=lambda c: c[5])]
        auto = "AUTOINCREMENT" in sql.upper() or (len(pk) == 1 and tipo_pg(next(c[2] for c in cols if c[1] == pk[0])) == "bigint" and pk[0] == "id")
        unicos = []
        for idx in src.execute(f'PRAGMA index_list("{nome}")').fetchall():
            if idx[2] and idx[3] == "u":  # unique, criado por UNIQUE(...) na tabela
                unicos.append([r[2] for r in src.execute(f'PRAGMA index_info("{idx[1]}")')])
        tabelas.append({"nome": nome, "cols": cols, "pk": pk, "auto": auto, "unicos": unicos})
    return tabelas


def ddl(t: dict) -> str:
    linhas = []
    for _cid, nome, tipo, notnull, dflt, _pk in t["cols"]:
        tp = tipo_pg(tipo)
        if t["auto"] and nome == "id":
            linhas.append("id bigint GENERATED BY DEFAULT AS IDENTITY")
            continue
        partes = [f'"{nome}"', tp]
        if notnull:
            partes.append("NOT NULL")
        if dflt is not None:
            partes.append(f"DEFAULT {dflt}")
        linhas.append(" ".join(partes))
    if t["pk"]:
        linhas.append("PRIMARY KEY (" + ", ".join(f'"{c}"' for c in t["pk"]) + ")")
    for u in t["unicos"]:
        linhas.append("UNIQUE (" + ", ".join(f'"{c}"' for c in u) + ")")
    return f'CREATE TABLE "{t["nome"]}" (\n  ' + ",\n  ".join(linhas) + "\n)"


def converter(valor, tipo: str):
    """O SQLite aceita qualquer coisa em qualquer coluna; o Postgres não."""
    if valor is None:
        return None
    if tipo == "bigint":
        if isinstance(valor, (int, bool)):
            return int(valor)
        try:
            return int(float(str(valor).strip()))
        except ValueError:
            return None
    if tipo == "double precision":
        try:
            return float(valor)
        except (TypeError, ValueError):
            return None
    if isinstance(valor, bytes):
        return valor.decode("utf-8", "replace")
    return str(valor).replace("\x00", "")


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--sqlite", default=str(RAIZ / "data" / "paes_med_ai.db"))
    ap.add_argument("--schema", default="public")
    ap.add_argument("--recriar", action="store_true", help="apaga as tabelas do app no esquema antes")
    args = ap.parse_args()

    load_dotenv(RAIZ / "backend" / ".env")
    url = os.getenv("DATABASE_URL", "").strip()
    if not url.startswith(("postgres://", "postgresql://")):
        print("DATABASE_URL ausente no backend/.env")
        return 1
    if not re.fullmatch(r"[a-z_][a-z0-9_]*", args.schema):
        print("Nome de esquema inválido")
        return 1

    src = sqlite3.connect(f"file:{Path(args.sqlite).as_posix()}?mode=ro", uri=True)
    tabelas = ler_tabelas(src)
    indices = [
        sql for (sql,) in src.execute(
            "SELECT sql FROM sqlite_master WHERE type='index' AND sql IS NOT NULL"
        )
    ]

    with psycopg.connect(url, prepare_threshold=None, connect_timeout=15) as pg:
        # o usuário do app (paes_app) não cria esquema; o "paes" já vem criado pelo administrador
        if not pg.execute("SELECT 1 FROM pg_namespace WHERE nspname = %s", (args.schema,)).fetchone():
            pg.execute(f'CREATE SCHEMA "{args.schema}"')
        pg.execute(f'SET search_path TO "{args.schema}"')
        existentes = {r[0] for r in pg.execute(
            "SELECT table_name FROM information_schema.tables WHERE table_schema = %s", (args.schema,)
        )}
        for t in tabelas:
            if t["nome"] in existentes:
                if not args.recriar:
                    print(f"Tabela {t['nome']} já existe em {args.schema}; use --recriar")
                    return 1
                pg.execute(f'DROP TABLE "{t["nome"]}" CASCADE')
        for t in tabelas:
            pg.execute(ddl(t))
            pg.execute(f'ALTER TABLE "{t["nome"]}" ENABLE ROW LEVEL SECURITY')
            nomes = [c[1] for c in t["cols"]]
            tipos = [("bigint" if (t["auto"] and c[1] == "id") else tipo_pg(c[2])) for c in t["cols"]]
            lista = ", ".join(f'"{n}"' for n in nomes)
            total = 0
            with pg.cursor().copy(f'COPY "{t["nome"]}" ({lista}) FROM STDIN') as cp:
                for row in src.execute(f'SELECT {lista} FROM "{t["nome"]}"'):
                    cp.write_row([converter(v, tp) for v, tp in zip(row, tipos, strict=True)])
                    total += 1
            if t["auto"]:
                pg.execute(
                    f"SELECT setval(pg_get_serial_sequence('\"{args.schema}\".\"{t['nome']}\"', 'id'), "
                    f'COALESCE((SELECT MAX(id) FROM "{t["nome"]}"), 0) + 1, false)'
                )
            print(f"{t['nome']:<20} {total:>6} linhas")
        for sql in indices:
            pg.execute(re.sub(r"CREATE (UNIQUE )?INDEX (IF NOT EXISTS )?", r"CREATE \1INDEX IF NOT EXISTS ", sql, flags=re.I))
        pg.commit()
    print(f"Pronto: {len(tabelas)} tabelas em {args.schema}.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
